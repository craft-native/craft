import AppKit

let width = 660
let height = 400
let appX = 166
let applicationsX = width - appX
let iconY = 169

func color(_ red: CGFloat, _ green: CGFloat, _ blue: CGFloat, alpha: CGFloat = 1) -> NSColor {
    NSColor(srgbRed: red, green: green, blue: blue, alpha: alpha)
}

func drawBackground() {
    // Paint a gentle vertical tint without dithering to keep the embedded TIFF small.
    for y in 0..<height {
        let progress = CGFloat(y) / CGFloat(height - 1)
        color(0.92 + 0.06 * progress, 0.94 + 0.05 * progress, 0.98 + 0.02 * progress).setFill()
        NSRect(x: 0, y: y, width: width, height: 1).fill()
    }

    // Finder's icon centers are measured from the top of the artwork.
    let centerY = height - iconY
    for centerX in [appX, applicationsX] {
        let rect = NSRect(x: centerX - 79, y: centerY - 73, width: 158, height: 146)
        let tile = NSBezierPath(roundedRect: rect.insetBy(dx: 0.5, dy: 0.5), xRadius: 27, yRadius: 27)
        color(1, 1, 1, alpha: 0.58).setFill()
        tile.fill()
        color(0.63, 0.70, 0.83, alpha: 0.35).setStroke()
        tile.lineWidth = 1
        tile.stroke()
    }

    let arrow = NSBezierPath()
    arrow.move(to: NSPoint(x: 269, y: centerY))
    arrow.line(to: NSPoint(x: 391, y: centerY))
    arrow.move(to: NSPoint(x: 379, y: centerY + 12))
    arrow.line(to: NSPoint(x: 391, y: centerY))
    arrow.line(to: NSPoint(x: 379, y: centerY - 12))
    arrow.lineWidth = 2.5
    arrow.lineCapStyle = .round
    arrow.lineJoinStyle = .round
    color(0.32, 0.40, 0.58).setStroke()
    arrow.stroke()

    let centered = NSMutableParagraphStyle()
    centered.alignment = .center
    ("Drag the app to Applications" as NSString).draw(
        in: NSRect(x: 0, y: 67, width: width, height: 32),
        withAttributes: [
            .font: NSFont.systemFont(ofSize: 24, weight: .semibold),
            .foregroundColor: color(0.13, 0.18, 0.27),
            .paragraphStyle: centered,
        ]
    )
}

// Render at each backing scale so the lettering and strokes are rasterized at native resolution.
func render(scale: Int, to url: URL) throws {
    let bitmap = NSBitmapImageRep(
        bitmapDataPlanes: nil, pixelsWide: width * scale, pixelsHigh: height * scale,
        bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
        colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0
    )!
    NSGraphicsContext.saveGraphicsState()
    let context = NSGraphicsContext(bitmapImageRep: bitmap)!
    NSGraphicsContext.current = context
    context.cgContext.scaleBy(x: CGFloat(scale), y: CGFloat(scale))
    drawBackground()
    NSGraphicsContext.restoreGraphicsState()
    try bitmap.representation(using: .png, properties: [:])!.write(to: url)
}

let scratch = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
try FileManager.default.createDirectory(at: scratch, withIntermediateDirectories: false)
defer { try? FileManager.default.removeItem(at: scratch) }
let standard = scratch.appendingPathComponent("installer.png")
let retina = scratch.appendingPathComponent("installer@2x.png")
let tiff = scratch.appendingPathComponent("installer.tiff")
try render(scale: 1, to: standard)
try render(scale: 2, to: retina)

let combine = Process()
combine.executableURL = URL(fileURLWithPath: "/usr/bin/tiffutil")
combine.arguments = ["-cathidpicheck", standard.path, retina.path, "-out", tiff.path]
try combine.run()
combine.waitUntilExit()
guard combine.terminationStatus == 0 else { exit(combine.terminationStatus) }

let output = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
    .appendingPathComponent("src/installer-background.ts")
let base64 = try Data(contentsOf: tiff).base64EncodedString(options: [.lineLength76Characters, .endLineWithLineFeed])
let module = """
/** Generated by scripts/generate-installer-background.swift. */
export const installerBackgroundFile = '\(tiff.lastPathComponent)'
export const installerIconPositions = { appX: \(appX), applicationsX: \(applicationsX), y: \(iconY) }
export const installerBackgroundBase64 = `
\(base64)
`

"""
try module.write(to: output, atomically: true, encoding: .utf8)
